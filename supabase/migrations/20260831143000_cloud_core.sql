create policy profiles_read_own on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy profiles_update_own on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
create policy workspaces_read_member on public.workspaces for select to authenticated using (private.is_workspace_member(id));
create policy members_read_member on public.workspace_members for select to authenticated using (private.is_workspace_member(workspace_id));
create policy providers_read_member on public.provider_connections for select to authenticated using (private.is_workspace_member(workspace_id));
create policy routes_read_member on public.routes for select to authenticated using (private.is_workspace_member(workspace_id));
create policy targets_read_member on public.route_targets for select to authenticated using (private.can_access_route(route_id));
create policy keys_read_member on public.virtual_api_keys for select to authenticated using (private.is_workspace_member(workspace_id));
create policy usage_read_member on public.request_usage for select to authenticated using (private.is_workspace_member(workspace_id));
create policy audit_read_member on public.audit_events for select to authenticated using (private.is_workspace_member(workspace_id));

